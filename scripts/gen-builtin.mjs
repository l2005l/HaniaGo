// Regenerates src/builtin.js from the destination data in public/index.html.
// Run after changing the built-in destinations: node scripts/gen-builtin.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const h = readFileSync(new URL('../public/index.html', import.meta.url), 'utf8');
const cut = (a, b) => h.slice(h.indexOf(a), h.indexOf(b, h.indexOf(a)));
const A = (n, la, lo, who, min, a, c, rec) => ({ n, la, lo, who, min, a, c, rec });
const DEST = new Function('A', cut('var DEST={', 'var HOME=') + ';return DEST')(A);
const WARN = new Function(cut('var WARN={', 'function fitOf') + ';return WARN')();
const EN = new Function(cut('var EN={', ';') + ';return EN')();
const out = {};
for (const k of Object.keys(DEST)) { const d = DEST[k]; out[k] = { n: d.n, en: EN[k] || k, abroad: !!d.abroad, fl: d.fl || 0, dur: d.dur || 0, hotelP: d.hotel.p, at: d.at.map((x) => ({ ...x, note: WARN[x.n] || '' })) }; }
writeFileSync(new URL('../src/builtin.js', import.meta.url), '// Generated by scripts/gen-builtin.mjs. Do not edit by hand.\nexport const BUILTIN = ' + JSON.stringify(out) + ';\n');
console.log(Object.keys(out).map((k) => k + ':' + out[k].at.length).join(' '));
