CREATE TABLE IF NOT EXISTS trips (device TEXT PRIMARY KEY, state TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS reports (
  id TEXT PRIMARY KEY, device TEXT NOT NULL, dest TEXT NOT NULL, place TEXT NOT NULL,
  kind TEXT NOT NULL, topic TEXT NOT NULL, text TEXT NOT NULL, min_age INTEGER, max_age INTEGER,
  src TEXT NOT NULL, src_name TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT '', ts INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS reports_dest ON reports (dest);
CREATE INDEX IF NOT EXISTS reports_device ON reports (device, ts);
CREATE TABLE IF NOT EXISTS clicks (id INTEGER PRIMARY KEY AUTOINCREMENT, partner TEXT NOT NULL, dest TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS counters (k TEXT PRIMARY KEY, n INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS cache (k TEXT PRIMARY KEY, v TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS dests (k TEXT PRIMARY KEY, json TEXT NOT NULL, ts INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS rail (from_st TEXT NOT NULL, dep INTEGER NOT NULL, arr INTEGER NOT NULL, days TEXT NOT NULL);
CREATE INDEX IF NOT EXISTS rail_from ON rail (from_st, arr);
